// Claude Code 2.1.310 runs the Stop hook before it writes the turn's
// entries: the prompt is on disk, no entry with the answer is yet, and the
// result says so (Pending), so the hook can read again. A found prompt, no
// prompt before the answer, or the same answer ending the turn before is
// not pending: reading again would change nothing.
func TestPromptBeforePending(t *testing.T) {
	const answer = "It is 14 degrees and cloudy in Paris."
	phone := prompt(" What is the weather in Paris?", "2026-10-25T17:16:31.123Z")
	for _, c := range []struct {
		name        string
		content     string
		ok, pending bool
	}{
		{"the turn's prompt written, its answer not yet", phone + others, false, true},
		{"only a tool call written after the prompt", phone + use("toolu_1", "Bash", bashInput), false, true},
		{"the answer written", phone + others + answerEntry(answer), true, false},
		{"no prompt before the answer", answerEntry(answer), false, false},
		{"the same answer in the turn before", prompt(" first", "2026-10-25T17:10:00.000Z") + answerEntry(answer) + phone + answerEntry(answer), false, false},
	} {
		t.Run(c.name, func(t *testing.T) {
			got, ok := promptBefore(t, c.content, answer)
			if ok != c.ok || got.Pending != c.pending || got.Unfinished {
				t.Fatalf("PromptBefore = %+v, %v; want ok %v, pending %v", got, ok, c.ok, c.pending)
			}
		})
	}
}

// A last line still being written leaves the newest entry unknown: no
// prompt, the result says why, as LastPrompt's.
func TestPromptBeforeUnfinishedLine(t *testing.T) {
	const answer = "It is 14 degrees and cloudy in Paris."
	turn := prompt(" What is the weather in Paris?", "2026-10-25T17:16:31.123Z") + answerEntry(answer)
	next := prompt(" And in Lyon?", "2026-10-25T17:18:01.000Z")
	got, ok := promptBefore(t, turn+next[:len(next)/2], answer)
	if ok || got.Text != "" || !got.Unfinished {
		t.Fatalf("PromptBefore = %+v, %v; want none, the last line unfinished", got, ok)
	}
}

// Only the last 8 MiB are read, as LastPrompt reads them: an answer or a
// prompt before them is not found. Lines longer than the chunks the file
// is read in come back whole.
func TestPromptBeforeWindow(t *testing.T) {
	const answer = "It is 14 degrees and cloudy in Paris."
	filler := `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"` + strings.Repeat("y", 1000) + `"}]}}` + "\n"
	var pad strings.Builder
	for pad.Len() <= promptWindow {
		pad.WriteString(filler)
	}
	phone := prompt(" What is the weather in Paris?", "2026-10-25T17:16:31.123Z")
	if got, ok := promptBefore(t, phone+answerEntry(answer)+pad.String(), answer); ok || !got.Pending {
		t.Fatalf("PromptBefore = %+v, %v; want none, pending: the answer before the window is not seen", got, ok)
	}
	if _, ok := promptBefore(t, phone+pad.String()+answerEntry(answer), answer); ok {
		t.Fatal("found a prompt before the window")
	}
	long := strings.Repeat("It is raining in Paris. ", 8_000) // ~190 KiB, over three chunks
	big := `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"` + strings.Repeat("x", 150<<10) + `"}]}}` + "\n"
	if got, ok := promptBefore(t, phone+big+answerEntry(long)+big, long); !ok || got.Text != " What is the weather in Paris?" {
		t.Fatalf("PromptBefore = %q, %v; want the phone's prompt", got.Text, ok)
	}
}

