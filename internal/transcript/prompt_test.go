// Lines longer than the chunks the file is read in come back whole.
func TestLastPromptLongLines(t *testing.T) {
	long := " " + strings.Repeat("please check the queue ", 10_000) // ~230 KiB
	big := `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"` + strings.Repeat("x", 150<<10) + `"}]}}` + "\n"
	got, ok := lastPrompt(t, prompt(" older prompt", "2026-10-25T17:10:00.000Z")+prompt(long, "2026-10-25T17:16:31.123Z")+big+others)
	if !ok || got.Text != long {
		t.Fatalf("LastPrompt = %d chars (ok %v), want %d", len(got.Text), ok, len(long))
	}
}

// Only the last 8 MiB are read: a prompt before them is not found, even
// in a file that holds no other.
func TestLastPromptReadsAtMost8MiB(t *testing.T) {
	p := filepath.Join(t.TempDir(), "t.jsonl")
	f, err := os.Create(p)
	if err != nil {
		t.Fatal(err)
	}
	w := bufio.NewWriter(f)
	w.WriteString(prompt(" run the tests", "2026-10-25T17:16:31.123Z"))
	filler := `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"` + strings.Repeat("y", 1000) + `"}]}}` + "\n"
	for n := 0; n <= 8<<20; n += len(filler) {
		w.WriteString(filler)
	}
	if err := w.Flush(); err != nil {
		t.Fatal(err)
	}
	f.Close()
	if got, ok, err := LastPrompt(p); err != nil || ok {
		t.Fatalf("LastPrompt = %q, %v, %v; want none", got.Text, ok, err)
	}
	// The same file with a prompt at its end finds that one.
	appendTo(t, p, prompt(" check the queue", "2026-10-25T17:30:00.000Z")+others)
	if got, ok, err := LastPrompt(p); err != nil || !ok || got.Text != " check the queue" {
		t.Fatalf("LastPrompt = %q, %v, %v", got.Text, ok, err)
	}
}

// A prompt counts only when its whole line is in the window: one that
// starts right at the window's first byte is found, one that starts a
// byte before it is not.
func TestLastPromptWindowEdge(t *testing.T) {
	outside := prompt(" outside the window", "2026-10-25T17:10:00.000Z")
	edge := prompt(" at the edge", "2026-10-25T17:16:31.123Z")
	for _, c := range []struct {
		name string
		size int // the file's size
		ok   bool
	}{
		{"starts at the window", len(outside) + promptWindow, true},
		{"starts a byte before it", len(outside) + promptWindow + 1, false},
	} {
		t.Run(c.name, func(t *testing.T) {
			// Pad with assistant lines of 1000 bytes, the last one sized
			// so the file is exactly c.size bytes.
			var b strings.Builder
			b.WriteString(outside + edge)
			line := func(n int) string {
				const head, tail = `{"type":"assistant","text":"`, `"}` + "\n"
				return head + strings.Repeat("z", n-len(head)-len(tail)) + tail
			}
			for c.size-b.Len() > 2000 {
				b.WriteString(line(1000))
			}
			b.WriteString(line(c.size - b.Len()))
			if b.Len() != c.size {
				t.Fatalf("built %d bytes, want %d", b.Len(), c.size)
			}
			got, ok := lastPrompt(t, b.String())
			if ok != c.ok || (ok && got.Text != " at the edge") {
				t.Fatalf("LastPrompt = %q, %v; want ok %v", got.Text, ok, c.ok)
			}
		})
	}
}

