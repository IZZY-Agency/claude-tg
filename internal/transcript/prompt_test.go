// A last line without its newline is still being written: the newest
// entry is unknown, so no prompt is found (ruling P13), even when an
// older phone prompt comes before it, and the result says why. Once its
// newline is there, it is the last prompt.
func TestLastPromptUnfinishedLine(t *testing.T) {
	const phone = " run the tests"
	mac := prompt("typed at the Mac", "2026-10-25T17:17:00.000Z")
	before := prompt(phone, "2026-10-25T17:16:31.123Z") + others
	for _, c := range []struct {
		name, content string
	}{
		{"a half-written user line", before + mac[:len(mac)/2]},
		{"a whole entry without its newline", before + strings.TrimSuffix(mac, "\n")},
		{"a half-written assistant line", before + `{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"On i`},
	} {
		t.Run(c.name, func(t *testing.T) {
			got, ok := lastPrompt(t, c.content)
			if ok || got.Text != "" || !got.Unfinished {
				t.Fatalf("LastPrompt = %+v, %v; want none, the last line unfinished", got, ok)
			}
		})
	}
	got, ok := lastPrompt(t, before+mac)
	if !ok || got.Text != "typed at the Mac" || got.Unfinished {
		t.Fatalf("LastPrompt = %+v, %v; want the Mac's prompt", got, ok)
	}
	if got, ok := lastPrompt(t, before); !ok || got.Unfinished {
		t.Fatalf("LastPrompt = %+v, %v; want the phone's prompt", got, ok)
	}
}

