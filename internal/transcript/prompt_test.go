// A turn is phone-started when its last prompt is a line the relay
// recorded (state.Session.SentFromPhone), as the hooks decide it: a
// background task's notification, another agent's message or an
// auto-compact continues the phone's turn, while a slash command or an
// interruption typed at the Mac after it, text typed at the Mac that
// Claude Code injects into the running turn, or the phone's line typed
// again at the Mac 3 minutes later, makes it a Mac turn. The phone's own
// text, injected into a busy session's turn, is the phone's, and so is a
// follow-up the relay queued in a busy session that Claude Code took in
// minutes later (ruling P15).
func TestPhoneStartedTurns(t *testing.T) {
	recorded := time.Date(2026, 10, 25, 17, 16, 31, 0, time.UTC)
	sess := &state.Session{SessionID: "s"}
	sess.RecordPhoneLine("run the tests", recorded, false)
	sess.RecordPhoneLine("and then deploy", recorded.Add(30*time.Second), true)
	phone := prompt(" run the tests", "2026-10-25T17:16:31.123Z") + others
	for _, c := range []struct {
		name    string
		content string
		want    bool
	}{
		{"the phone's prompt", phone, true},
		{"a task notification after it", phone + userEntry(quote("<task-notification>\n<status>completed</status>\n</task-notification>"), "") + others, true},
		{"a slash command after it", phone + userEntry(quote("<command-name>/compact</command-name>\n<command-message>compact</command-message>\n<command-args></command-args>"), ""), false},
		{"an interruption after it", phone + userEntry(`[{"type":"text","text":"[Request interrupted by user]"}]`, ""), false},
		{"the same line typed at the Mac 3 minutes later", phone + prompt("run the tests", "2026-10-25T17:19:31.123Z"), false},
		{"Mac text injected into the running turn", phone + queued(quote("also update the docs"), "prompt", "human", "2026-10-25T17:17:00.000Z") + others, false},
		{"the phone's text injected into a busy session's turn", prompt(" older prompt", "2026-10-25T17:10:00.000Z") + queued(quote(" run the tests"), "prompt", "human", "2026-10-25T17:16:45.000Z") + others, true},
		{"a queued task notification after it", phone + queued(quote("<task-notification>done</task-notification>"), "task-notification", "human", "2026-10-25T17:17:00.000Z"), true},
		{"another agent's message after it", phone + queued(quote("peer: build is green"), "prompt", "peer", "2026-10-25T17:17:00.000Z"), true},
		{"an auto-compact after it", phone + userEntry(quote("This session is being continued from a previous conversation."), `"isCompactSummary":true,`) + others, true},
		{"a phone follow-up queued in the busy session, taken in 5 minutes later", phone + queued(quote(" and then deploy"), "prompt", "human", "2026-10-25T17:22:01.000Z") + others, true},
		{"the same follow-up written as a user entry 5 minutes later", phone + prompt(" and then deploy", "2026-10-25T17:22:01.000Z") + others, true},
		{"the phone's idle line typed at the Mac 5 minutes later", phone + prompt("run the tests", "2026-10-25T17:21:31.000Z"), false},
		{"no prompt", others, false},
	} {
		t.Run(c.name, func(t *testing.T) {
			p, ok := lastPrompt(t, c.content)
			if got := ok && sess.SentFromPhone(p.Text, p.At); got != c.want {
				t.Fatalf("phone-started = %v (prompt %q at %v), want %v", got, p.Text, p.At, c.want)
			}
		})
	}
}

// answerEntry is an assistant entry holding one text part, as Claude Code
