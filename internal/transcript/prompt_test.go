// The prompt of the turn that gave an answer is the owner's prompt right
// before the newest entry with the answer's text, by LastPrompt's rules:
// a prompt written after that entry (a follow-up queued to the busy
// session, which Claude Code took in as the turn ended) is the next
// turn's, not it. No entry with the answer, no prompt before it, or the
// same answer ending the turn before (the newest assistant text before
