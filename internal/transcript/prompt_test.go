// prompt is a prompt entry as Claude Code writes one: the relay's text keeps
// the leading space it was typed with.
func prompt(text, ts string) string {
	return `{"parentUuid":"a1","isSidechain":false,"type":"user","message":{"role":"user","content":` + quote(text) + `},"uuid":"u1","timestamp":"` + ts + `","promptId":"p1"}` + "\n"
}

// userEntry is a user entry with the given raw content and extra fields.
func userEntry(content, extra string) string {
	return `{"type":"user",` + extra + `"message":{"role":"user","content":` + content + `},"timestamp":"2026-10-25T17:20:00.000Z"}` + "\n"
}

// queued is the attachment Claude Code writes when it injects text queued
// for a busy session into the running turn, with prompt (raw JSON),
// commandMode and origin kind.
func queued(prompt, mode, kind, ts string) string {
	return `{"type":"attachment","attachment":{"type":"queued_command","commandMode":"` + mode + `","origin":{"kind":"` + kind + `"},"prompt":` + prompt + `,"timestamp":"2026-10-25T17:20:00.000Z"},"timestamp":"` + ts + `","uuid":"q1"}` + "\n"
}

func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`)
	return `"` + r.Replace(s) + `"`
}

// others are entries of the kinds a prompt search must step over.
const others = `{"type":"assistant","timestamp":"2026-10-25T17:16:40.000Z","message":{"role":"assistant","content":[{"type":"text","text":"On it."}]}}` + "\n" +
	`{"type":"attachment","attachment":{"type":"x"},"timestamp":"2026-10-25T17:16:41.000Z"}` + "\n" +
	`{"type":"system","subtype":"turn_duration","durationMs":5}` + "\n" +
	`{"type":"queue-operation","operation":"enqueue","content":"queued text"}` + "\n" +
	`{"type":"api-request","requestId":"req_1"}` + "\n"

func lastPrompt(t *testing.T, content string) (Prompt, bool) {
	t.Helper()
	p := filepath.Join(t.TempDir(), "t.jsonl")
	write(t, p, content)
	got, ok, err := LastPrompt(p)
	if err != nil {
		t.Fatalf("LastPrompt: %v", err)
	}
	return got, ok
}

